function convertToUa(text) {
  let result = String(text ?? "").replace(/\s+/g, " ").trim();
  for (const [from, to] of MAP) result = result.split(from).join(to);
  return result;
}

const file = new URL("./data.js", import.meta.url);
const raw = await fs.readFile(file, "utf8");
const prefix = raw.match(/^﻿?window\.FLAKS_DATA\s*=\s*/)?.[0] ?? "window.FLAKS_DATA = ";
const data = JSON.parse(raw.replace(/^﻿?window\.FLAKS_DATA\s*=\s*/, "").replace(/;\s*$/, ""));

let changedNames = 0;
for (const p of data.products) {
  const ua = convertToUa(p.nameRu);
  if (ua !== p.nameUa) changedNames++;
  p.nameUa = ua;
  p.sectionUa = convertToUa(p.sectionRu);
  p.categoryUa = convertToUa(p.categoryRu);
}
let changedCats = 0;
for (const c of data.categories) {
  const ua = convertToUa(c.ru);
  if (ua !== c.ua) changedCats++;
  c.ua = ua;
}

const write = process.argv.includes("--write");

if (!write) {
  console.log("=== CATEGORY ua (ru -> new ua) ===");
  for (const c of data.categories) console.log(`  ${c.ru}  ->  ${c.ua}`);
  console.log("\n=== SAMPLE PRODUCT nameUa ===");
  for (const idx of [0, 1621, 3183, 4972, 6755, 7779, 9465, 10088, 11600, 12036]) {
    if (data.products[idx]) console.log(`  [${data.products[idx].sku}] ${data.products[idx].nameUa}`);
  }
  // Surface any remaining obvious Russian letters specific markers in names.
  const ruRemnant = data.products.filter((p) => /(сверл|метчик|фрез|резьб|червяч|пластин[ыо]|ступиц|концев|дисков|развертк|зенков|зенкер)/i.test(p.nameUa));
  console.log(`\nNames with possible RU remnants: ${ruRemnant.length}`);
  ruRemnant.slice(0, 12).forEach((p) => console.log(`  [${p.sku}] ${p.nameUa}`));
  console.log(`\nWould change: ${changedNames} product names, ${changedCats} category names. (dry-run, no write)`);
} else {
  await fs.writeFile(file, `${prefix}${JSON.stringify(data)};\n`, "utf8");
  console.log(`data.js rewritten: ${changedNames} product names, ${changedCats} category names updated.`);
}
